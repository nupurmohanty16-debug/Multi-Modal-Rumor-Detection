def step_on_batch(model, batch, lossf):
    if len(batch)==2:
        x,y=batch; y=y.to(DEVICE, dtype=torch.long)
        if isinstance(x, dict): x={k:v.to(DEVICE) for k,v in x.items()}; logits=model(x)
        else: x=x.to(DEVICE); logits=model(x)
    else:
        enc,im,y=batch
        enc={k:v.to(DEVICE) for k,v in enc.items()}; im=im.to(DEVICE); y=y.to(DEVICE, dtype=torch.long)
        logits=model(enc,im)
    loss=lossf(logits,y); preds=torch.argmax(logits,dim=1)
    return loss, preds.detach().cpu(), y.detach().cpu(), logits.detach().cpu()

def train_one_epoch(model, loader, opt, lossf):
    model.train(); tot=0.0
    for batch in loader:
        opt.zero_grad()
        loss,_,_,_=step_on_batch(model,batch,lossf)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        opt.step(); tot+=loss.item()
    return tot/max(1,len(loader))

@torch.no_grad()
def eval_collect(model, loader):
    model.eval(); ys, ps, pr = [], [], []
    for batch in loader:
        _, preds, y, logits = step_on_batch(model, batch, nn.CrossEntropyLoss())
        prob_pos = F.softmax(logits, dim=1)[:,1]
        ys.append(y); pr.append(preds); ps.append(prob_pos)
    y_true=torch.cat(ys).numpy(); y_pred=torch.cat(pr).numpy(); y_prob=torch.cat(ps).numpy()
    return y_true, y_pred, y_prob

def show_confusion_matrix(y_true,y_pred,normalize=False,labels=(0,1),title="Confusion Matrix"):
    cm = confusion_matrix(y_true,y_pred,labels=labels,normalize='true' if normalize else None)
    fig,ax=plt.subplots(figsize=(4.5,4)); im=ax.imshow(cm,interpolation='nearest',cmap='Blues'); ax.figure.colorbar(im,ax=ax)
    ax.set(xticks=np.arange(len(labels)), yticks=np.arange(len(labels)),
           xticklabels=[str(l) for l in labels], yticklabels=[str(l) for l in labels],
           ylabel='True label', xlabel='Predicted label', title=title)
    th=cm.max()/2.
    for i in range(cm.shape[0]):
        for j in range(cm.shape[1]):
            txt=f"{cm[i,j]:.2f}" if normalize else f"{int(cm[i,j])}"
            ax.text(j,i,txt,ha="center",va="center",color="white" if cm[i,j]>th else "black")
    plt.tight_layout(); plt.show()

def show_roc_pr_curves(y_true, y_prob, title_prefix=""):
    if len(np.unique(y_true))<2:
        print("ROC/PR curves require both classes present in y_true; skipping."); return None
    fpr,tpr,_=roc_curve(y_true,y_prob); roc_auc=auc(fpr,tpr)
    prec,rec,_=precision_recall_curve(y_true,y_prob); ap=average_precision_score(y_true,y_prob)
    plt.figure(figsize=(5,4)); plt.plot(fpr,tpr,lw=2,label=f"AUC = {roc_auc:.3f}"); plt.plot([0,1],[0,1],'--'); plt.xlabel("FPR"); plt.ylabel("TPR"); plt.title(f"{title_prefix} ROC"); plt.legend(); plt.tight_layout(); plt.show()
    plt.figure(figsize=(5,4)); plt.plot(rec,prec,lw=2,label=f"AP = {ap:.3f}"); plt.xlabel("Recall"); plt.ylabel("Precision"); plt.title(f"{title_prefix} PR"); plt.legend(); plt.tight_layout(); plt.show()
    return {"auc":roc_auc,"ap":ap}

def evaluate_all(model, loader, name="Model"):
    y_true,y_pred,y_prob=eval_collect(model,loader)
    acc=accuracy_score(y_true,y_pred); f1m=f1_score(y_true,y_pred,average='macro'); f1w=f1_score(y_true,y_pred,average='weighted')
    print(f"\n=== {name} ==="); print(f"Accuracy: {acc:.4f} | F1-macro: {f1m:.4f} | F1-weighted: {f1w:.4f}\n")
    print("Classification report:"); print(classification_report(y_true,y_pred,digits=4, zero_division=0))
    show_confusion_matrix(y_true,y_pred,normalize=False,title=f"{name} – Confusion Matrix (Counts)")
    show_confusion_matrix(y_true,y_pred,normalize=True,title=f"{name} – Confusion Matrix (Normalized)")
    curves=show_roc_pr_curves(y_true,y_prob,title_prefix=name)
    if curves is not None: print(f"AUC: {curves['auc']:.4f} | Average Precision (AP): {curves['ap']:.4f}")
    return {"name":name, "acc":acc, "f1_macro":f1m, "f1_weighted":f1w,
            "auc":None if curves is None else curves["auc"],
            "ap": None if curves is None else curves["ap"],
            "y_true":y_true, "y_pred":y_pred, "y_prob":y_prob}

