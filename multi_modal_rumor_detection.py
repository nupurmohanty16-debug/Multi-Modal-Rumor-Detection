def run_experiment(model_ctor, train_dl, val_dl, lr_list=(1e-4,5e-5), drop_list=(0.1,0.3), epochs=3, label="EXP"):
    best={"f1":-1,"cfg":None,"state":None}
    for lr in lr_list:
        for dr in drop_list:
            set_global_seed(SEED)
            model=model_ctor(dropout=dr).to(DEVICE)
            opt=torch.optim.AdamW(model.parameters(), lr=lr)
            lossf=make_weighted_ce(train_df)
            print(f"\n[{label}] lr={lr} dropout={dr}")
            for ep in range(epochs):
                tr=train_one_epoch(model, train_dl, opt, lossf)
                print(f"  Epoch {ep+1} Train Loss: {tr:.4f}")
                metrics=evaluate_all(model, val_dl, name=f"{label} (val)")
            if metrics["f1_macro"]>best["f1"]:
                best={"f1":metrics["f1_macro"], "cfg":(lr,dr),
                      "state":{k:v.detach().cpu() for k,v in model.state_dict().items()}}
    print(f"\nBest F1={best['f1']:.4f} with lr={best['cfg'][0]} drop={best['cfg'][1]}")
    return best
