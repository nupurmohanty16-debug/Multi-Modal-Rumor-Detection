def mask_mean(last_hidden_state, attention_mask):
    mask = attention_mask.unsqueeze(-1)
    s = (last_hidden_state * mask).sum(1)
    d = mask.sum(1).clamp(min=1)
    return s / d

class TextOnlyBERT(nn.Module):
    def __init__(self, model_name='bert-base-chinese', dropout=0.2, use_cls=False):
        super().__init__()
        self.bert=AutoModel.from_pretrained(model_name)
        h=self.bert.config.hidden_size; self.use_cls=use_cls
        self.head=nn.Sequential(nn.Dropout(dropout), nn.Linear(h,2))
    def forward(self, tx):
        out=self.bert(**tx)
        t = out.pooler_output if (self.use_cls and hasattr(out,"pooler_output") and out.pooler_output is not None) \
            else mask_mean(out.last_hidden_state, tx["attention_mask"])
        return self.head(t)

class ImageOnlyResNet(nn.Module):
    def __init__(self, arch='resnet18', pretrained=True, dropout=0.3):
        super().__init__()
        if arch=='resnet18':
            self.backbone=models.resnet18(weights=models.ResNet18_Weights.DEFAULT if pretrained else None)
        elif arch=='resnet50':
            self.backbone=models.resnet50(weights=models.ResNet50_Weights.DEFAULT if pretrained else None)
        else: raise ValueError("arch must be resnet18 or resnet50")
        feat=self.backbone.fc.in_features
        self.backbone.fc=nn.Sequential(nn.Dropout(dropout), nn.Linear(feat,2))
    def forward(self,im): return self.backbone(im)

class LateFusionStrong(nn.Module):
    def __init__(self, model_name='bert-base-chinese', img_arch='resnet18', dropout=0.3):
        super().__init__()
        self.txt=AutoModel.from_pretrained(model_name); tdim=self.txt.config.hidden_size
        self.img = models.resnet18(weights=models.ResNet18_Weights.DEFAULT) if img_arch=='resnet18' else models.resnet50(weights=models.ResNet50_Weights.DEFAULT)
        idim=self.img.fc.in_features; self.img.fc=nn.Identity()
        self.head=nn.Sequential(nn.Linear(tdim+idim,256), nn.ReLU(), nn.Dropout(dropout), nn.Linear(256,2))
    def forward(self,tx,im):
        t_last=self.txt(**tx).last_hidden_state
        t=mask_mean(t_last, tx["attention_mask"]); i=self.img(im)
        return self.head(torch.cat([t,i],dim=1))

class EarlyFusion(nn.Module):
    def __init__(self, model_name='bert-base-chinese', img_arch='resnet18', n_layers=1, n_heads=8, dropout=0.1):
        super().__init__()
        self.txt=AutoModel.from_pretrained(model_name); H=self.txt.config.hidden_size
        img=models.resnet18(weights=models.ResNet18_Weights.DEFAULT) if img_arch=='resnet18' else models.resnet50(weights=models.ResNet50_Weights.DEFAULT)
        idim=img.fc.in_features; img.fc=nn.Identity(); self.img=img; self.img_proj=nn.Linear(idim,H)
        enc=nn.TransformerEncoderLayer(d_model=H, nhead=n_heads, dropout=dropout, batch_first=True)
        self.fuser=nn.TransformerEncoder(enc, num_layers=n_layers)
        self.head=nn.Sequential(nn.Dropout(dropout), nn.Linear(H,2))
    def forward(self,tx,im):
        t_out=self.txt(**tx).last_hidden_state
        iv=self.img_proj(self.img(im)).unsqueeze(1)
        x=torch.cat([iv,t_out],dim=1)
        pad=None
        if "attention_mask" in tx:
            B,L=tx["attention_mask"].shape
            pad=(1-tx["attention_mask"]).bool()
            pad=torch.cat([torch.zeros(B,1,dtype=torch.bool,device=pad.device), pad], dim=1)
        z=self.fuser(x, src_key_padding_mask=pad)
        return self.head(z[:,0,:])

class AttentionFusion(nn.Module):
    def __init__(self, model_name='bert-base-chinese', img_arch='resnet18', heads=8, dropout=0.1):
        super().__init__()
        self.txt=AutoModel.from_pretrained(model_name); H=self.txt.config.hidden_size
        img=models.resnet18(weights=models.ResNet18_Weights.DEFAULT) if img_arch=='resnet18' else models.resnet50(weights=models.ResNet50_Weights.DEFAULT)
        idim=img.fc.in_features; img.fc=nn.Identity(); self.img=img; self.img_proj=nn.Linear(idim,H)
        self.attn=nn.MultiheadAttention(embed_dim=H, num_heads=heads, batch_first=True, dropout=dropout)
        self.head=nn.Sequential(nn.Linear(2*H,256), nn.ReLU(), nn.Dropout(dropout), nn.Linear(256,2))
    def forward(self,tx,im):
        t_last=self.txt(**tx).last_hidden_state
        t_mask=tx.get("attention_mask", None)
        iv=self.img_proj(self.img(im)).unsqueeze(1)
        key_padding=(t_mask==0) if t_mask is not None else None
        attended,_=self.attn(query=iv, key=t_last, value=t_last, key_padding_mask=key_padding)
        t_pooled=mask_mean(t_last, tx["attention_mask"])
        return self.head(torch.cat([attended.squeeze(1), t_pooled], dim=1))

