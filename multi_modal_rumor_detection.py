def parse_labeled_file(path: P, label: int, split: str):
    rows=[]
    with open(path, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            line=line.strip()
            if not line: continue
            if line.startswith("{") and line.endswith("}"):
                try:
                    j = json.loads(line); pid=None; txt=""
                    for k in ["post_id","id","weibo_id","mid"]:
                        if k in j: pid=str(j[k]); break
                    for k in ["text","content","weibo_text","tweet"]:
                        if k in j: txt=str(j[k]); break
                    if pid and txt:
                        m=re.search(r"(\d{6,})", pid)
                        if m: rows.append({"post_id": m.group(1), "text": txt, "label": label, "split": split}); continue
                except Exception: pass
            matched=False
            for sep in ["\t","|||","|",",",":",";"]:
                if sep in line:
                    a,b = [x.strip() for x in line.split(sep,1)]
                    m=re.search(r"(\d{6,})", a)
                    if m: rows.append({"post_id": m.group(1), "text": b, "label": label, "split": split}); matched=True; break
            if matched: continue
            m=re.search(r"(\d{6,})", line)
            if m:
                pid=m.group(1); txt=line.replace(pid,"").strip(" |,:;\t-")
                rows.append({"post_id": pid, "text": txt, "label": label, "split": split})
    df = pd.DataFrame(rows).dropna().reset_index(drop=True)
    if not df.empty:
        df["len"]=df["text"].astype(str).str.len()
        df=df.sort_values("len", ascending=False).drop_duplicates("post_id").drop(columns=["len"])
    return df

