def try_open_rgb(path):
    p = P(path)
    try:
        with Image.open(p) as im: return im.convert("RGB")
    except Exception:
        return None

class TextOnlyDS(Dataset):
    def __init__(self, frame, tokenizer, max_len=128):
        self.df=frame.reset_index(drop=True); self.tok=tokenizer; self.max_len=max_len
    def __len__(self): return len(self.df)
    def __getitem__(self,i):
        r=self.df.iloc[i]
        enc=self.tok(str(r["text"]), padding='max_length', truncation=True, max_length=self.max_len, return_tensors='pt')
        enc={k:v.squeeze(0) for k,v in enc.items()}
        return enc, int(r["label"])

class ImageOnlyDS(Dataset):
    def __init__(self, frame): self.df=frame.reset_index(drop=True)
    def __len__(self): return len(self.df)
    def __getitem__(self,i):
        r=self.df.iloc[i]; img=try_open_rgb(r["image_path"])
        if img is None: raise FileNotFoundError(r["image_path"])
        return IMG_TFMS(img), int(r["label"])

class MultiModalDS(Dataset):
    def __init__(self, frame, tokenizer, max_len=128):
        self.df=frame.reset_index(drop=True); self.tok=tokenizer; self.max_len=max_len
    def __len__(self): return len(self.df)
    def __getitem__(self,i):
        r=self.df.iloc[i]
        enc=self.tok(str(r["text"]), padding='max_length', truncation=True, max_length=self.max_len, return_tensors='pt')
        enc={k:v.squeeze(0) for k,v in enc.items()}
        img=try_open_rgb(r["image_path"])
        if img is None: raise FileNotFoundError(r["image_path"])
        return enc, IMG_TFMS(img), int(r["label"])

def _seeded_generator():
    g=torch.Generator(); g.manual_seed(SEED); return g

def _oversample_sampler(labels):
    # inverse-frequency sampling
    labels = np.asarray(labels, dtype=int)
    class_counts = np.bincount(labels + (labels.min()==1)) if labels.min()>0 else np.bincount(labels)
    class_counts = class_counts[class_counts>0]
    weights = 1.0 / class_counts
    sample_weights = [weights[y] for y in labels]
    return WeightedRandomSampler(sample_weights, num_samples=len(sample_weights), replacement=True)

