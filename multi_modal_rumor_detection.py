def make_weighted_ce(train_df):
    # class-weighted CE for imbalance
    _, counts = np.unique(train_df["label"].values, return_counts=True)
    total = counts.sum()
    weights = total / (len(counts) * counts)
    w = torch.tensor(weights, dtype=torch.float32, device=DEVICE)
    return nn.CrossEntropyLoss(weight=w)

def best_threshold_from_val(model, val_loader):
    # maximize macro-F1 on val by scanning thresholds
    y_true, _, y_prob = eval_collect(model, val_loader)
    best_t, best_f1 = 0.5, -1.0
    for t in np.linspace(0.05, 0.95, 19):
        y_hat = (y_prob >= t).astype(int)
        f1 = f1_score(y_true, y_hat, average='macro')
        if f1>best_f1: best_f1, best_t = f1, t
    print(f"Best threshold on val for macro-F1: t={best_t:.2f} (F1={best_f1:.4f})")
    return best_t

